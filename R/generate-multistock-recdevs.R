#' Generate Multi-Stock Recruitment Deviations
#'
#' Generates projection recruitment deviations for the stocks of a
#' multi-stock operating model, with cross-stock correlation for stocks whose
#' historical deviations were supplied, and identical deviations for stocks
#' that share recruitment.
#'
#' @param OM An operating model object of class [om-class].
#' @param TruncSD Numeric scalar or `NULL` (default). Number of standard
#'   deviations at which the log deviations are bounded, as in [GenRecDevs()].
#'   `NULL` uses each stock's `SRR@TruncSD`.
#' @param silent `logical(1)` Display messages?
#' @param overwrite `logical`, length `nStock(OM)`, or `NULL` (default).
#'   Controls which stocks' `RecDevProj` are written. `NULL` overwrites every
#'   stock. Stocks with `overwrite = FALSE` keep their existing `RecDevProj`
#'   (e.g. user-supplied values) untouched, but their historical deviations
#'   still contribute to the estimated cross-stock correlation.
#' @param Correlated `NULL`, `TRUE`, or `FALSE`. Which stocks' projection
#'   deviations are correlated. Defaults to `OM@Control$CorrelatedRecDevs`.
#'   `NULL` correlates stocks whose historical deviations (`SRR@RecDevHist`)
#'   were supplied, e.g. by the user or imported from an assessment; `TRUE`
#'   correlates all stocks; `FALSE` correlates none.
#'
#' @return The input `OM` object with `RecDevProj` populated for all stocks
#'   and simulations (subject to `overwrite`).
#'
#' @details
#'
#' The projection deviations of each stock have the marginal standard
#' deviation `SRR@SD`, lag-1 autocorrelation `SRR@AC`, and truncation
#' `TruncSD`, as for a single-stock operating model ([GenRecDevs()]). The
#' historical deviations determine only the cross-stock correlation and the
#' starting point of the autocorrelated projection series.
#'
#' Within each simulation, stocks whose historical deviations
#' (`SRR@RecDevHist[sim, ]`) are identical are treated as a single
#' group: one series is simulated for the group and copied to every
#' member, so linked stocks (e.g. a female/male pair sharing recruitment)
#' stay identical in the projection period.
#'
#' Groups selected by `Correlated` are correlated using the correlation of
#' their historical log deviations. Historical deviations that are generated
#' from `SRR@SD` and `SRR@AC` are independent random draws, so by default
#' (`Correlated = NULL`) stocks with generated historical deviations have
#' independent projection deviations. The projection deviations of a stock
#' that is not correlated with any other stock, has no identical stocks, and
#' recruits in every time step are those generated by [PopulateSRR()].
#'
#' The AR(1) process runs on a unit-variance latent scale that carries the
#' cross-stock correlation:
#'
#' \deqn{
#'   Z_t = \Phi Z_{t-1} + \epsilon_t, \quad
#'   \epsilon_t \sim MVN(0, \Sigma_\epsilon)
#' }
#'
#' where \eqn{\Phi} is a diagonal matrix of lag-1 autocorrelation
#' coefficients (`SRR@AC`) and \eqn{\Sigma_\epsilon} is derived by
#' [CalcInnovationCov()] from the cross-stock correlation matrix. The latent
#' series is transformed to log deviations with standard deviation `SRR@SD`.
#'
#' In seasonal operating models, seasons in which a stock's historical
#' deviations are all zero (no recruitment) have zero projection deviations.
#'
#' @seealso [GenRecDevs()], [CalcInnovationCov()], [OMControl]
#' @export
GenMultiStockRecDevs <- function(OM, TruncSD = NULL, silent = FALSE, overwrite = NULL,
                                 Correlated = OM@Control$CorrelatedRecDevs) {

  CheckPackage('MASS')

  .CheckClass(OM)
  .CheckCorrelatedRecDevs(Correlated)
  Saved <- .SaveRNG()
  on.exit(.RestoreRNG(Saved), add = TRUE)

  nSim      <- OM@nSim
  n_stock   <- nStock(OM)
  ProjYears <- Years(OM, "P")
  pYear     <- length(ProjYears)
  nSeason   <- max(1L, as.integer(OM@Seasons %||NA% 1))

  if (n_stock < 2) return(OM)

  if (is.null(overwrite)) overwrite <- rep(TRUE, n_stock)
  if (length(overwrite) != n_stock)
    cli::cli_abort("`overwrite` must be length `nStock(OM)` ({n_stock})", .internal = TRUE)

  Trunc <- purrr::map_dbl(OM@Stock, \(stock) TruncSD %||% stock@SRR@TruncSD %||% 3)
  Eligible <- if (is.null(Correlated)) {
    purrr::map_lgl(OM@Stock, \(stock) isTRUE(stock@SRR@Misc$RecDevHistSupplied))
  } else rep(Correlated, n_stock)

  show <- .MsgShowProgress(silent)
  pb <- if (show) {
    cli::cli_progress_bar(
      name = "Simulating recruitment deviations for projection period",
      total = nSim,
      clear = TRUE
    )
  }

  for (sim in seq_len(nSim)) {

    if (show) cli::cli_progress_update(pb, set = sim)
    .SetRNG(.SeedInt(OM@Seed %||% 101, 'MultiStockRecDev', .GlobalSim(OM, sim)))

    # Extract stats
    RecDevStats <- purrr::map(OM@Stock, \(stock)
                              .GetRecDevStats(stock@SRR, sim)
    ) |> dplyr::bind_rows() |> as.data.frame()

    # Extract historical deviations
    RecDevHist <- purrr::map(OM@Stock, \(stock) {
      recdevhist <- stock@SRR@RecDevHist
      if (dim(recdevhist)[1] < sim) return(recdevhist[1, ])
      recdevhist[sim, ]
    }) |> dplyr::bind_rows() |> as.data.frame()

    grp     <- .IdenticalRecDevGroups(RecDevHist)
    rep_idx <- match(unique(grp), grp)
    n_grp   <- length(rep_idx)
    members <- lapply(rep_idx, \(r) which(grp == grp[r]))

    RecDevStatsGrp <- RecDevStats[rep_idx, , drop = FALSE]
    RecDevHistGrp  <- RecDevHist[rep_idx, , drop = FALSE]
    TruncGrp       <- Trunc[rep_idx]
    nHistTS        <- ncol(RecDevHistGrp)

    active_phase <- matrix(TRUE, nrow = n_grp, ncol = nSeason)
    for (g in seq_len(n_grp)) {
      for (p in seq_len(nSeason)) {
        cols  <- seq(p, nHistTS, by = nSeason)
        known <- as.numeric(RecDevHistGrp[g, cols])
        known <- known[!is.na(known)]
        if (length(known) && all(known == 0)) active_phase[g, p] <- FALSE
      }
    }
    hist_phase <- ((seq_len(nHistTS) - 1) %% nSeason) + 1
    proj_phase <- ((nHistTS + seq_len(pYear) - 1) %% nSeason) + 1
    ActiveHist <- active_phase[, hist_phase, drop = FALSE]
    ActiveProj <- active_phase[, proj_phase, drop = FALSE]

    sd_grp <- RecDevStatsGrp$sd
    phi    <- RecDevStatsGrp$ac

    for (g in seq_len(n_grp)) {
      inactive_na <- which(!ActiveHist[g, ] & is.na(RecDevHistGrp[g, ]))
      if (length(inactive_na)) RecDevHistGrp[g, inactive_na] <- 0

      active_cols <- which(ActiveHist[g, ])
      na_ind <- active_cols[is.na(RecDevHistGrp[g, active_cols])]
      if (!length(na_ind)) next

      prior_active <- active_cols[active_cols < na_ind[1]]
      zl_prev <- if (length(prior_active)) {
        .DevToLatent(log(as.numeric(RecDevHistGrp[g, max(prior_active)])),
                     sd_grp[g], TruncGrp[g])
      } else 0

      for (k in seq_along(na_ind)) {
        zl_prev <- phi[g] * zl_prev + rnorm(1) * sqrt(1 - phi[g]^2)
        RecDevHistGrp[g, na_ind[k]] <- exp(.LatentToDev(zl_prev, sd_grp[g], TruncGrp[g]))
      }
    }

    corr_grp <- vapply(members, \(m) any(Eligible[m]), logical(1))
    R_latent <- diag(n_grp)
    if (sum(corr_grp) > 1)
      R_latent[corr_grp, corr_grp] <- .HistRecDevCor(RecDevHistGrp[corr_grp, , drop = FALSE],
                                                     ActiveHist[corr_grp, , drop = FALSE])

    Sigma_eps <- CalcInnovationCov(R_latent, phi)

    Zl_prev <- vapply(seq_len(n_grp), function(g) {
      active_cols <- which(ActiveHist[g, ])
      if (!length(active_cols)) return(0)
      z_last <- log(as.numeric(RecDevHistGrp[g, max(active_cols)]))
      if (!is.finite(z_last)) return(0)
      .DevToLatent(z_last, sd_grp[g], TruncGrp[g])
    }, numeric(1))

    Zl_proj <- matrix(NA_real_, nrow = n_grp, ncol = pYear)

    # Sample latent innovations
    if (all(abs(Sigma_eps) < 1e-12)) {
      eps_mat <- matrix(0, nrow = pYear, ncol = n_grp)
    } else {
      eig <- eigen(Sigma_eps, symmetric = TRUE)
      if (any(eig$values <= 1e-10))
        Sigma_eps <- Sigma_eps + diag(1e-8, nrow(Sigma_eps))

      eps_mat <- MASS::mvrnorm(pYear, mu = rep(0, n_grp), Sigma = Sigma_eps)
      if (n_grp == 1) eps_mat <- matrix(eps_mat, ncol = 1)
    }

    for (t in seq_len(pYear)) {
      active_t <- ActiveProj[, t]
      Zl_prev[active_t] <- phi[active_t] * Zl_prev[active_t] + eps_mat[t, active_t]
      Zl_proj[, t] <- Zl_prev
    }

    for (g in seq_len(n_grp)) {
      m <- members[[g]]
      keep <- length(m) == 1 && all(active_phase[g, ]) && all(R_latent[g, -g] == 0) &&
        .HasRecDevProj(OM@Stock[[m]]@SRR, sim, pYear)
      if (keep) next
      proj_dev  <- rep(0, pYear)
      active_t  <- ActiveProj[g, ]
      proj_dev[active_t] <- exp(.LatentToDev(Zl_proj[g, active_t], sd_grp[g], TruncGrp[g]))
      for (st in m) {
        if (!overwrite[st]) next
        OM@Stock[[st]]@SRR@RecDevProj[sim, ] <- proj_dev
      }
    }

  } # end sim loop
  if (show) cli::cli_progress_done(pb)
  OM
}

.CheckCorrelatedRecDevs <- function(Correlated) {
  if (is.null(Correlated) || (is.logical(Correlated) && length(Correlated) == 1 && !is.na(Correlated)))
    return(invisible(TRUE))
  cli::cli_abort(c(
    "x" = "{.code OM@Control$CorrelatedRecDevs} must be {.code NULL}, {.code TRUE}, or {.code FALSE}.",
    "i" = "See {.topic MSEtool::OMControl}."
  ), call = NULL)
}

# Cross-stock correlation of historical log deviations; identity where it can't be estimated
.HistRecDevCor <- function(RecDevHist, ActiveHist) {
  n <- nrow(RecDevHist)
  R <- diag(n)
  use_cols <- which(vapply(seq_len(ncol(RecDevHist)), function(j) {
    col <- as.numeric(RecDevHist[, j])
    !any(col == 1 | is.na(col)) && all(ActiveHist[, j])
  }, logical(1)))
  if (length(use_cols) < 3) return(R)

  log_hist <- log(as.matrix(RecDevHist[, use_cols, drop = FALSE]))
  Sigma_Z  <- stats::cov(t(log_hist))
  if (any(eigen(Sigma_Z, symmetric = TRUE)$values < 0))
    Sigma_Z <- as.matrix(Matrix::nearPD(Sigma_Z)$mat)

  active <- diag(Sigma_Z) > 0
  if (sum(active) > 1)
    R[active, active] <- stats::cov2cor(Sigma_Z[active, active, drop = FALSE])
  R
}

.HasRecDevProj <- function(SRR, sim, pYear) {
  x <- SRR@RecDevProj
  d <- dim(x)
  length(d) == 2 && d[1] >= sim && d[2] == pYear && !anyNA(x[sim, ])
}

.GetRecDevStats <- function(SRR, sim = 1) {

  # SD/AC may be a [Sim, Year] array or a plain per-sim vector
  pick <- function(x, nm) {
    if (!length(x) || any(!is.finite(x)))
      cli::cli_abort("Non-finite or empty {.code SRR@{nm}}", .internal = TRUE)
    d <- dim(x)
    as.numeric(if (is.null(d)) x[min(sim, length(x))] else x[min(sim, d[1]), 1])
  }

  c(sd = pick(SRR@SD, "SD"), ac = pick(SRR@AC, "AC"))
}

.IdenticalRecDevGroups <- function(RecDevHist) {
  n   <- nrow(RecDevHist)
  grp <- seq_len(n)
  if (n < 2) return(grp)

  for (i in seq_len(n - 1)) {
    if (anyNA(RecDevHist[i, ])) next
    for (j in seq(i + 1, n)) {
      if (grp[j] == grp[i] || anyNA(RecDevHist[j, ])) next
      if (identical(as.numeric(RecDevHist[i, ]), as.numeric(RecDevHist[j, ])))
        grp[j] <- grp[i]
    }
  }
  grp
}


