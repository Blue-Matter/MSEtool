#' Populate an Operating Model
#'
#' Populate a complete operating model (`om` object) by populating all
#' component objects (stocks, fleets, observation models, and derived
#' structures), performing internal consistency checks, and initializing
#' simulation-specific values.
#'
#' @param OM An [OM()] object to populate.
#' @param silent Logical. If `TRUE`, suppress informational messages and
#'   warnings during population.
#' @param force Logical. If `TRUE`, force re-population even if the internal
#'   object digest indicates no changes since the last call.
#' @param standardize_effort Logical. Used internally. Apply [StandardizeEffort()]?
#' @param adjust_fecundity  Logical. Used internally. Apply [AdjustSeasonalFecundity()]?
#'
#' @details
#' 
#' This function is typically called internally, but may also be called directly.
#' 
#' `PopulateOM()` is the top-level population routine for operating models.
#' It orchestrates population of all model components, including:
#'
#' * Stocks via [PopulateStock()]
#' * Fleets via [PopulateFleet()]
#' * Implementation models (`imp`)
#' * Observation models (`obs`)
#'
#' For multi-stock `OM`s, projection recruitment deviations are generated by
#' [GenMultiStockRecDevs()]. Each stock's deviations have standard deviation
#' `SRR@SD` and autocorrelation `SRR@AC`, and stocks with identical
#' historical deviations share one projection series. By default, stocks
#' whose historical deviations were supplied (e.g. imported from an
#' assessment) are correlated using the correlation of those deviations, and
#' stocks with generated historical deviations are independent. See
#' `CorrelatedRecDevs` in [OMControl].
#'
#' To avoid unnecessary recomputation, a digest of the operating model is
#' checked before population. If the digest is unchanged and `force = FALSE`,
#' the input object is returned unchanged.
#'
#' @return
#' An [OM()] object populated with simulation- and time-specific values.
#'
#' @seealso
#' [Populate()], [PopulateStock()], [PopulateFleet()]
#'
#' @examples
#' \dontrun{
#' OM <- PopulateOM(OM)
#'
#' }
#'
#' @export
PopulateOM <- function(OM, 
                       silent = FALSE, 
                       force = FALSE, 
                       standardize_effort = TRUE,
                       adjust_fecundity = TRUE) {
  
  .CheckClass(OM)
  Saved <- .SaveRNG()
  on.exit(.RestoreRNG(Saved), add = TRUE)
  
  OM <- UpdateObject(OM) |> .RepairSimDimnames()
  if (!length(OM@maxF)) OM@maxF <- 3
  
  if (EmptyObject(OM)) return(OM)
  if (.CheckDigest(OM) & !force) return(OM)
  .WarnSeedChanged(OM)

  OM <- .DropStaleSims(OM)

  if (is.null(OM@Stock))
    cli::cli_abort(c(
      "x" = "{.var OM} must have at least one stock",
      "i" = "See {.help MSEtool::OM} and {.help MSEtool::Stock}"
    ))
  
  if (is.null(OM@Fleet)) 
    cli::cli_abort(c(
      "x" = "{.var OM} must have at least one fleet",
      "i" = "See {.help MSEtool::OM} and {.help MSEtool::Fleet}"
    ))

  .MsgStep("Populating OM", "Populated OM", silent)

  StockListRaw <- if (inherits(OM@Stock, 'stock')) list(OM@Stock) else OM@Stock
  auto_proj <- purrr::map_lgl(StockListRaw, \(st) EmptyObject(st@SRR@RecDevProj))

  OM <- OM |>
    .PopulateStockList(silent = silent, force = force) |>
    .GenerateMultiStockRecDevs(overwrite = auto_proj, silent = silent) |>
    .PopulateFleetList(silent = silent, force = force) |>
    .PopulateComplexes() |>
    .PopulateImpList(silent = silent) |>
    .ProcessData() |>
    .PopulateObsList(silent = silent) |>
    .ProcessDataNames() |>
    .UpdateSPFrom() |>
    .ValidateSPFrom() |>
    .ShareSPFromSRR() |>
    .CheckAlphaBetaSRR() |>
    .RepairSimDimnames()

  .CheckOMReady(OM)

  if (adjust_fecundity)
    OM <- AdjustSeasonalFecundity(OM, silent = silent)

  if (standardize_effort)
    OM <- StandardizeEffort(OM, populate=FALSE)

  OM <- .RefreshFleetDigests(OM)
  OM@Misc$PopulatedSeed <- OM@Misc$PopulatedSeed %||% OM@Seed

  .SetDigest(OM)
}

.WarnSeedChanged <- function(OM) {
  Old <- OM@Misc$PopulatedSeed
  if (is.null(Old) || identical(as.numeric(Old), as.numeric(OM@Seed %||% 101)))
    return(invisible())
  cli::cli_warn(c(
    "!" = "{.var Seed} was changed from {.val {Old}} to {.val {OM@Seed}} after the OM was populated.",
    "i" = "Values already generated with {.code Seed = {Old}} (e.g., recruitment deviations, observation error) are not redrawn.",
    "i" = "Set {.var Seed} before the OM is populated, e.g., import with {.code Seed = {OM@Seed}}, or with {.code Populate = FALSE}, then set {.var Seed} and call {.fn Populate}."
  ), call = NULL)
}

.FleetSeed <- function(OM, st, fl) paste(OM@Seed %||% 101, 'Fleet', st, fl, sep = '_')

.RefreshFleetDigests <- function(OM) {
  if (is.null(OM@Fleet) || !inherits(OM@Fleet, "StockFleetList")) return(OM)
  for (st in seq_along(OM@Fleet)) {
    Stock <- OM@Stock[[st]]
    for (fl in seq_along(OM@Fleet[[st]])) {
      seed <- .FleetSeed(OM, st, fl)
      OM@Fleet[[st]][[fl]] <- .SetDigest(OM@Fleet[[st]][[fl]], .FleetArgList(Stock, seed))
    }
  }
  OM
}

.ProcessData <- function(OM) {
  if (is.null(OM@Data)) {
    return(OM)
  }
  stocknames <- StockNames(OM)

  if (isS4(OM@Data)) {
    if (length(stocknames) > 1) {
      stocknames <- paste(stocknames, collape = "-")
    }
    OM@Data <- MakeNamedList(stocknames, OM@Data)
  }

  if (is.list(OM@Data) & is.null(names(OM@Data))) {
    names(OM@Data) <- stocknames
  }

  .ProcessDataBiology(OM)
}

# Data@LifeHistory by stock and Data@Exploitation by stock and fleet
.ProcessDataBiology <- function(OM) {
  Complexes <- OM@Complexes
  StockNms  <- StockNames(OM)
  FleetNms  <- FleetNames(OM)

  for (i in seq_along(OM@Data)) {
    Data <- OM@Data[[i]]
    if (!isS4(Data) || i > length(Complexes)) next
    Where <- paste0("OM@Data[[", i, "]]@")
    Nms   <- StockNms[Complexes[[i]]]
    Data@LifeHistory  <- .NormalizeLifeHistoryData(Data@LifeHistory, Nms, paste0(Where, "LifeHistory"))
    Data@Exploitation <- .NormalizeExploitationData(Data@Exploitation, Nms, FleetNms,
                                                    paste0(Where, "Exploitation"))
    OM@Data[[i]] <- Data
  }
  OM
}

.ProcessDataNames <- function(OM) {
  if (is.null(OM@Data)) return(OM)
  FleetNms  <- FleetNames(OM)

  # CPUE/Survey names and rows are resolved by .AlignIndicesData() during conditioning
  for (i in seq_along(OM@Data)) {
    Data <- OM@Data[[i]]
    if (!isS4(Data)) next
    Slots <- c("Effort", "Landings", "Discards", "LandingsAtAge", "DiscardsAtAge",
               "LandingsAtSize", "DiscardsAtSize")
    HasValue <- vapply(Slots, \(sl) !is.null(slot(Data, sl)@Value), logical(1))
    if (any(HasValue) && !length(Data@Years))
      cli::cli_abort(c(
        "x" = "{.code OM@Data[[{i}]]@Years} is not set.",
        "i" = "Set {.code Years} in {.fn Data} to the calendar years covered by the data."
      ))
    for (sl in Slots[HasValue])
      slot(Data, sl) <- .ResolveDataNames(slot(Data, sl), Data@Years, FleetNms, sl, i)
    OM@Data[[i]] <- Data
  }
  OM
}

.ResolveDataNames <- function(obj, Years, FleetNms, slotName, i) {
  if (is.null(obj@Value)) return(obj)
  Where    <- paste0("OM@Data[[", i, "]]@", slotName)
  Value    <- .AddDataYearDimnames(obj@Value, Years, paste0(Where, "@Value"))
  nCol     <- dim(Value)[2]
  ColNames <- dimnames(Value)[[2]]

  Name <- obj@Name %||% ColNames
  if (is.null(Name) && nCol == length(FleetNms)) Name <- FleetNms
  if (is.null(Name))
    cli::cli_abort("{.code {Where}} has no names: set {.code {Where}@Name} or the column names of {.code {Where}@Value}.")
  if (length(Name) != nCol)
    cli::cli_abort("{.code {Where}@Name} has {length(Name)} element{?s} but {.code {Where}@Value} has {nCol} column{?s}.")
  if (!is.null(ColNames) && !identical(as.character(ColNames), as.character(Name)))
    cli::cli_abort(c(
      "x" = "{.code {Where}@Name} does not match the column names of {.code {Where}@Value}.",
      "i" = "{.code @Name}: {.val {Name}}; column names: {.val {ColNames}}."
    ))
  if (anyDuplicated(Name))
    cli::cli_abort("{.code {Where}@Name} has duplicated name{?s} {.val {unique(Name[duplicated(Name)])}}.")

  Unknown <- setdiff(Name, FleetNms)
  if (length(Unknown))
    cli::cli_abort(c(
      "x" = "{.code {Where}} has {cli::qty(length(Unknown))}name{?s} {.val {Unknown}} not found in {.code FleetNames(OM)}.",
      "i" = "Fleet names: {.val {FleetNms}}."
    ))
  Missing <- setdiff(FleetNms, Name)
  if (length(Missing))
    cli::cli_abort(c(
      "x" = "{.code {Where}} has no column for fleet{?s} {.val {Missing}}.",
      "i" = "Supply a column for every fleet in {.code FleetNames(OM)}, with {.code NA} where there are no data."
    ))
  ord <- match(FleetNms, Name)

  # projection reads fleet columns by position, so store them in FleetNames(OM) order
  obj@Name <- Name[ord]
  for (val in intersect(c("Value", "CV"), slotNames(obj))) {
    arr <- slot(obj, val)
    if (is.null(arr)) next
    arr <- .AddDataYearDimnames(arr, Years, paste0(Where, "@", val))
    if (dim(arr)[2] != nCol)
      cli::cli_abort("{.code {Where}@{val}} has {dim(arr)[2]} column{?s} but {.code {Where}@Value} has {nCol}.")
    dimnames(arr)[[2]] <- Name
    slot(obj, val) <- abind::asub(arr, ord, 2, drop = FALSE)
  }
  if (length(obj@Units) == nCol) obj@Units <- obj@Units[ord]
  if ("Classes" %in% slotNames(obj) && is.list(obj@Classes) && length(obj@Classes) == nCol)
    obj@Classes <- stats::setNames(obj@Classes[ord], obj@Name)
  obj
}

.AddDataYearDimnames <- function(arr, Years, Where) {
  if (length(dim(arr)) < 2) arr <- array(arr, dim = c(length(arr), 1))
  d  <- dim(arr)
  dn <- dimnames(arr)
  if (is.null(dn)) dn <- vector("list", length(d))
  dnn <- names(dn)
  if (is.null(dnn)) dnn <- rep("", length(d))
  dnn[1:2][dnn[1:2] == ""] <- c("Year", "Fleet")[dnn[1:2] == ""]
  names(dn) <- dnn

  if (is.null(dn[[1]])) {
    if (d[1] != length(Years))
      cli::cli_abort(c(
        "x" = "{.code {Where}} has {d[1]} row{?s} but {.code Data@Years} has {length(Years)} year{?s}.",
        "i" = "Add {.code Year} row names to identify the years, or supply one row per year in {.code Data@Years}."
      ))
    dn[[1]] <- Years
  }
  Outside <- dn[[1]][!round(as.numeric(dn[[1]]), 6) %in% round(as.numeric(Years), 6)]
  if (length(Outside))
    cli::cli_abort(c(
      "x" = "{.code {Where}} has {cli::qty(length(Outside))}row{?s} for year{?s} {.val {Outside}} not in {.code Data@Years}.",
      "i" = "{.code Data@Years} covers {min(Years)} to {max(Years)}."
    ))
  dimnames(arr) <- dn
  arr
}

.PopulateStockList <- function(OM, silent = FALSE, force = FALSE) {
  if (is.null(OM@Stock)) 
    return(OM)

  nStock <- nStock(OM)
  if (inherits(OM@Stock, 'stock')) {
    StockList <- list(OM@Stock)
  } else if (is.list(OM@Stock)) {
    StockList <- OM@Stock
  } else {
    cli::cli_abort(
      "`OM@Stock` must be an S4 Stock or a list of `Stock` objects"
    )
  }
  class(StockList) <- "StockList"

  show <- .MsgShowProgress(silent)
  if (show) cli::cli_progress_bar(format = "Populating stock {.stock {Stock@Name}}",
                                  total = nStock)
  for (st in seq_len(nStock)) {
    Stock <- StockList[[st]]
    Stock@nSim <- OM@nSim
    if (show) cli::cli_progress_update()
    StockList[[st]] <- PopulateStock(
      Stock = Stock,
      nYear = OM@nYear,
      pYear = OM@pYear,
      CurrentYear = OM@CurrentYear,
      nSim = OM@nSim,
      Seasons = OM@Seasons,
      seed = paste(OM@Seed %||% 101, 'Stock', st, sep = '_'),
      silent = silent,
      force = force
    )
    names(StockList)[st] <- StockList[[st]]@Name
  }
  if (show) cli::cli_progress_done()

  OM@Stock <- StockList
  OM
}


.GenerateMultiStockRecDevs <- function(OM, overwrite, silent = FALSE) {
  if (nStock(OM) < 2) return(OM)

  argList <- list(
    purrr::map(OM@Stock, \(s) s@SRR),
    OM@Seed, OM@nSim, Years(OM, "P"), OM@Seasons, overwrite,
    OM@Control$CorrelatedRecDevs
  )
  newDigest <- digest::digest(argList, algo = "spookyhash")
  if (isTRUE(identical(attr(OM, "RecDevDigest"), newDigest))) return(OM)

  OM <- GenMultiStockRecDevs(OM, silent = silent, overwrite = overwrite)
  attr(OM, "RecDevDigest") <- newDigest
  OM
}

.PopulateFleetList <- function(OM, silent = FALSE, force = FALSE) {
  
  if (is.null(OM@Fleet)) return(OM)
  
  StockList <- OM@Stock
  nStocks <- nStock(OM)
  nFleets <- nFleet(OM)
  
  FleetInput <- OM@Fleet
  if (isS4(FleetInput)) {
    # OM@Fleet = single `fleet` object: replicate across stocks
    FleetInput <- replicate(nStocks, list(FleetInput), simplify = FALSE)
  } else if (inherits(FleetInput, "FleetList")) {
    # OM@Fleet = list of `fleet` objects: replicate across stocks
    FleetInput <- replicate(nStocks, FleetInput, simplify = FALSE)
  } else {
    if (length(FleetInput) != 1 && length(FleetInput) != nStocks) {
      cli::cli_abort("`OM@Fleet` must be a list of length 1 or `nStock` ({.val {nStocks}})")
    }
    
    if (length(FleetInput) == 1) {
      # If OM@Fleet is a list of `fleet` objects but only provided for one stock,
      # replicate the FleetList over stocks
      FleetInput <- replicate(nStocks, FleetInput[[1]], simplify = FALSE)
    }
  }

  nFleetperStock <- lengths(FleetInput)
  if (length(unique(nFleetperStock)) != 1) 
    cli::cli_abort(
      "All stocks must have the same number of fleets. Currently: {.val {nFleetperStock}}"
    )
  
  FleetList <- vector("list", nStocks)
  class(FleetList) <- "StockFleetList"
  names(FleetList) <- names(StockList)
  for (st in seq_len(nStocks)) {
    FleetList[[st]] <- FleetInput[[st]]
    class(FleetList[[st]]) <- "FleetList"
  }
  
  show <- .MsgShowProgress(silent)
  if (show)
    cli::cli_progress_bar(
      format = "Populating fleet {.fleet {FleetList[[st]][[fl]]@Name}} (stock {.stock {names(StockList)[st]}}) {cli::pb_bar} {cli::pb_percent}",
      total = nStocks * nFleets
    )
  for (st in seq_len(nStocks)) {
    StockOrig <- StockList[[st]]

    needsUpdate <- force || any(vapply(seq_len(nFleets), function(fl) {
      !.CheckDigest(FleetList[[st]][[fl]], .FleetArgList(StockOrig, .FleetSeed(OM, st, fl)))
    }, logical(1)))

    ExtendedLength <- NULL
    ExtendedWeight <- NULL
    WeightFallback <- NULL
    if (needsUpdate) {
      Years <- CalcYears(
        nYear = StockOrig@nYear,
        pYear = StockOrig@pYear,
        CurrentYear = StockOrig@CurrentYear,
        Seasons = StockOrig@Seasons
      )
      ExtendedLength <- StockOrig@Length
      if (!is.null(ExtendedLength@ALK))
        ExtendedLength@ALK <- ExtendedLength@ALK |> ExtendSims(StockOrig@nSim) |> ExtendYears(Years)
      ExtendedWeight <- StockOrig@Weight
      if (!is.null(ExtendedWeight@MeanAtLength))
        ExtendedWeight@MeanAtLength <- ExtendedWeight@MeanAtLength |> ExtendSims(StockOrig@nSim) |> ExtendYears(Years)

      if (!is.null(ExtendedLength@ALK) && !is.null(ExtendedWeight@MeanAtLength))
        WeightFallback <- .AtSize2AtAge(ExtendedWeight, ExtendedLength, allow_shortcut = FALSE)
    }

    for (fl in seq_len(nFleets)) {
      if (show) cli::cli_progress_update()
      FleetList[[st]][[fl]] <- PopulateFleet(
        Fleet = FleetList[[st]][[fl]],
        Stock = StockOrig,
        seed = .FleetSeed(OM, st, fl),
        silent = silent,
        force  = force,
        WeightFallback = WeightFallback,
        ExtendedLength = ExtendedLength,
        ExtendedWeight = ExtendedWeight
      )

      # extract warning logs - only selectivity for now
      if (!is.null(FleetList[[st]][[fl]]@Selectivity@Misc$warning)) {
        warns <- FleetList[[st]][[fl]]@Selectivity@Misc
        warns$warning[[1]]$name <- paste(FleetList[[st]][[fl]]@Name, warns$warning[[1]]$name, sep = ' - ')
        OM@Log <- .JoinLog(OM@Log, warns)
      }
      
      names(FleetList[[st]])[fl] <- FleetList[[st]][[fl]]@Name
    }
  }
  if (show) cli::cli_progress_done()

  .CheckFleetMaximum(FleetList)
  OM@Fleet <- FleetList
  OM
}

# A fleet's maximum effort is a property of the fleet, so it must agree across stocks
.CheckFleetMaximum <- function(FleetList) {
  if (length(FleetList) < 2) return(invisible(TRUE))
  for (fl in seq_along(FleetList[[1]])) {
    Max <- purrr::map(FleetList, \(Fleets) Fleets[[fl]]@Effort@Maximum)
    Set <- !purrr::map_lgl(Max, is.null)
    if (!any(Set)) next
    Same <- all(Set) && all(purrr::map_lgl(Max[-1], \(m) isTRUE(all.equal(unname(m), unname(Max[[1]])))))
    if (!Same)
      cli::cli_abort(c(
        "x" = "Fleet {.val {FleetList[[1]][[fl]]@Name}}: {.code Effort@Maximum} differs between stocks.",
        "i" = "Set the same maximum effort for the fleet in every stock."
      ))
  }
  invisible(TRUE)
}


.PopulateComplexes <- function(OM) {
  if (length(OM@Complexes) > 0) {
    # Validate the user-supplied Complexes before proceeding.
    cx   <- OM@Complexes
    nStk <- nStock(OM)

    # Must be a fully named list.
    cx_nms <- names(cx)
    if (is.null(cx_nms) || any(cx_nms == "")) {
      bad <- which(is.null(cx_nms) | cx_nms == "")
      cli::cli_abort(c(
        "x" = "`OM@Complexes` must be a fully named list.",
        "i" = "Element{?s} {bad} {?is/are} unnamed."
      ))
    }

    # All index values must be integers in 1:nStock.
    all_idx <- unlist(cx)
    if (!is.numeric(all_idx) || any(all_idx != as.integer(all_idx))) {
      cli::cli_abort(c(
        "x" = "All values in `OM@Complexes` must be integer stock indices.",
        "i" = "Found non-integer value{?s}: {.val {unique(all_idx[all_idx != as.integer(all_idx)])}}."
      ))
    }
    all_idx <- as.integer(all_idx)
    if (any(all_idx < 1L) || any(all_idx > nStk)) {
      bad_idx <- sort(unique(all_idx[all_idx < 1L | all_idx > nStk]))
      cli::cli_abort(c(
        "x" = "`OM@Complexes` contains stock {?index/indices} out of range.",
        "i" = "`OM` has {nStk} stock{?s} (indices 1:{nStk}); found {.val {bad_idx}}."
      ))
    }

    # Every stock must belong to exactly one complex.
    if (length(all_idx) != nStk || !setequal(all_idx, seq_len(nStk))) {
      missing_idx <- setdiff(seq_len(nStk), all_idx)
      dup_idx     <- all_idx[duplicated(all_idx)]
      msgs <- character(0)
      if (length(missing_idx))
        msgs <- c(msgs, "i" = "Stock {?index/indices} not assigned to any complex: {.val {missing_idx}}.")
      if (length(dup_idx))
        msgs <- c(msgs, "i" = "Stock {?index/indices} assigned to more than one complex: {.val {unique(dup_idx)}}.")
      cli::cli_abort(c("x" = "Every stock must belong to exactly one complex.", msgs))
    }

    return(OM)
  }

  if (nStock(OM) == 1) {
    OM@Complexes <- MakeNamedList(StockNames(OM), 1)
    return(OM)
  }

  if (length(OM@Data) > 0) {
    if (length(OM@Data) == 1) {
      OM@Complexes <- MakeNamedList(names(OM@Data), 1:nStock(OM))
      return(OM)
    }

    if (length(OM@Data) == nStock(OM)) {
      OM@Complexes <- list()
      for (i in seq_along(OM@Stock)) {
        OM@Complexes[[i]] <- i
      }
      names(OM@Complexes) <- StockNames(OM)
      return(OM)
    }
  }
  
  # each stock is managed separately 
  stocks <- StockNames(OM)
  OM@Complexes <- setNames(
    as.list(seq_along(stocks)),
    stocks
  )
  
  OM
}

.PopulateImpList <- function(OM, silent = FALSE) {
  Complexes    <- Complexes(OM)
  nComplex     <- length(Complexes)
  ComplexNames <- names(Complexes)

  FleetNames <- FleetNames(OM)
  nFleet     <- length(FleetNames)
  if (is.null(FleetNames) || nFleet < 1) return(OM)

  HistYears <- Years(OM, "H")
  ProjYears <- Years(OM, "P")

  # Empty object — initialise with default imp for each complex and fleet
  if (EmptyObject(OM@Imp)) {
    OM@Imp <- MakeNamedList(ComplexNames, MakeNamedList(FleetNames, new("imp")))
    return(OM)
  }

  # Single imp object — replicate over complexes and fleets
  if (inherits(OM@Imp, "imp"))
    OM@Imp <- MakeNamedList(ComplexNames, MakeNamedList(FleetNames, OM@Imp))

  # Validate complex length
  if (length(OM@Imp) != nComplex)
    cli::cli_abort(c(
      "x" = "`OM@Imp` must be length `length(Complexes(OM))` ({nComplex})",
      "i" = "Currently length {.val {length(OM@Imp)}}"
    ))

  # Validate each complex has at least nFleet elements
  complex_lengths <- purrr::map_int(OM@Imp, length)
  if (any(complex_lengths < nFleet))
    cli::cli_abort(c(
      "x" = "Each element of `OM@Imp` must have at least `nFleet(OM)` ({nFleet}) element{?s}",
      "i" = "Currently length {.val {complex_lengths}}"
    ))

  # Validate all elements are imp objects
  cls <- purrr::map(OM@Imp, \(cx) purrr::map_chr(cx, class)) |> unlist()
  if (any(cls != "imp"))
    cli::cli_abort(c(
      "x" = "Each element of `OM@Imp[[cx]][[fl]]` must be a {.help MSEtool::Imp} object",
      "i" = "Currently class {.val {cls}}"
    ))

  # Build populated imp list indexed by complex then fleet
  ImpList <- vector("list", nComplex)
  names(ImpList) <- ComplexNames

  for (cx in seq_len(nComplex)) {
    imp_nms          <- names(OM@Imp[[cx]])
    ImpList[[cx]]    <- vector("list", nFleet)
    names(ImpList[[cx]]) <- FleetNames
    for (fl in seq_len(nFleet)) {
      .SetSeed(paste(OM@Seed %||% 101, 'Imp', cx, fl, sep = '_'))
      ImpList[[cx]][[fl]] <- PopulateImp(OM@Imp[[cx]][[fl]], OM@nSim, HistYears, ProjYears)
    }
  }

  OM@Imp <- ImpList
  OM
}

.PopulateObsList <- function(OM, silent = FALSE) {
  Complexes    <- Complexes(OM)
  nComplex     <- length(Complexes)
  ComplexNames <- names(Complexes)
  
  FleetNames <- FleetNames(OM)
  nFleet     <- length(FleetNames)
  if (is.null(FleetNames) || nFleet < 1) return(OM)
  
  # Empty object — initialise with fleet-only obs for conditioning
  if (EmptyObject(OM@Obs)) {
    OM@Obs <- MakeNamedList(ComplexNames, MakeNamedList(FleetNames, new("obs")))
    return(OM)
  }
  
  # Single obs object — replicate over complexes and fleets
  if (inherits(OM@Obs, "obs"))
    OM@Obs <- MakeNamedList(ComplexNames, MakeNamedList(FleetNames, OM@Obs))
  
  # Validate complex length
  if (length(OM@Obs) != nComplex)
    cli::cli_abort(c(
      'x' = "`OM@Obs` must be length `length(Complexes(OM))` ({nComplex})",
      'i' = "Currently length {.val {length(OM@Obs)}}"
    ))
  
  # Validate each complex has at least nFleet elements
  complex_lengths <- purrr::map_int(OM@Obs, length)
  if (any(complex_lengths < nFleet))
    cli::cli_abort(c(
      'x' = 'Each element of `OM@Obs` must have at least `nFleet(OM)` ({nFleet}) element{?s}',
      'i' = 'Currently length {.val {complex_lengths}}'
    ))
  
  # Validate all elements are obs objects
  cls <- purrr::map(OM@Obs, \(st) purrr::map_chr(st, class)) |> unlist()
  if (any(cls != 'obs'))
    cli::cli_abort(c(
      'x' = 'Each element of `OM@Obs[[st]][[fl]]` must be a {.help MSEtool::Obs} object',
      'i' = 'Currently class {.val {cls}}'
    ))
  
  # Validate survey names: elements beyond nFleet must be explicitly named
  # and all names within each complex must be unique
  for (st in seq_len(nComplex)) {
    obs_names  <- names(OM@Obs[[st]])
    nSurvey    <- length(OM@Obs[[st]]) - nFleet
    
    if (nSurvey > 0) {
      survey_names <- obs_names[seq(nFleet + 1, length(obs_names))]
      
      if (any(is.null(survey_names)) || any(nchar(survey_names) == 0))
        cli::cli_abort(c(
          'x' = 'Survey `Obs` objects in complex {.val {ComplexNames[[st]]}} must be explicitly named',
          'i' = 'Provide unique names for elements {nFleet + 1} to {length(obs_names)}'
        ))
      
      if (anyDuplicated(obs_names))
        cli::cli_abort(c(
          'x' = 'All names in `OM@Obs[[{st}]]` must be unique across fleets and surveys',
          'i' = 'Duplicated name{?s}: {.val {obs_names[duplicated(obs_names)]}}'
        ))
    }
  }
  
  # Build populated obs list, preserving fleet + survey structure per complex
  ObsList <- vector("list", nComplex)
  names(ObsList) <- ComplexNames
  
  for (st in seq_len(nComplex)) {
    obs_names            <- names(OM@Obs[[st]])
    nObs                 <- length(obs_names)
    ObsList[[st]]        <- vector("list", nObs)
    names(ObsList[[st]]) <- obs_names
    AgeClasses           <- OM@Stock[[st]]@Ages@Classes
    
    for (fl in seq_len(nObs)) {
      .SetSeed(paste(OM@Seed %||% 101, 'Obs', st, fl, sep = '_'))
      
      # Fleet obs use fleet-specific size classes; survey obs use NULL
      SizeClasses <- if (fl <= nFleet) {
        OM@Fleet[[st]][[fl]]@Selectivity@Classes
      } else {
        NULL
      }
      
      ObsList[[st]][[fl]] <- PopulateObs(Obs       = OM@Obs[[st]][[fl]],
                                         HistYears = Years(OM, "H"),
                                         ProjYears = Years(OM, "P"),
                                         nSim      = OM@nSim,
                                         AgeBins   = AgeClasses,
                                         SizeBins  = SizeClasses)
    }
  }
  
  OM@Obs <- ObsList
  OM
}

.UpdateSPFrom <- function(OM) {
  stocknames <- StockNames(OM)
  if (length(stocknames) != nStock(OM)) {
    cli::cli_abort(c('{.var Name} must be unique for each Stock.',
                     'i'='Current Stock Names are {.val {stocknames}}'))
  }
  for (st in 1:nStock(OM)) {
    SPFrom <- OM@Stock[[st]]@SRR@SPFrom
    if (is.null(SPFrom)) next

    nm <- names(SPFrom)
    if (!is.null(nm) && any(nzchar(nm))) {
      names(SPFrom) <- purrr::map_chr(nm, \(x) {
        idx <- suppressWarnings(as.numeric(x))
        if (nzchar(x) && !is.na(idx) && idx >= 1 && idx <= length(stocknames))
          return(stocknames[idx])
        x
      })
    } else if (is.numeric(SPFrom)) {
      SPFrom <- stocknames[SPFrom]
    }
    OM@Stock[[st]]@SRR@SPFrom <- SPFrom
  }
  OM
}


.ResolveSPFromWeights <- function(SPFrom, stockNames, selfIndex) {
  if (is.null(SPFrom))
    return(list(from = selfIndex, weight = 1))

  nm <- names(SPFrom)
  if (!is.null(nm) && any(nzchar(nm)))
    return(list(from = match(nm, stockNames), weight = unname(as.numeric(SPFrom))))

  src <- if (is.character(SPFrom)) match(SPFrom, stockNames) else as.integer(SPFrom)
  list(from = src, weight = 1)
}

.IsSPFromSelfOnly <- function(SPFrom, selfIndex, stockNames) {
  w <- .ResolveSPFromWeights(SPFrom, stockNames, selfIndex)
  length(w$from) == 1L && identical(w$from, selfIndex)
}

.SPFromConnectedGroups <- function(OM) {
  stockNames <- StockNames(OM)
  n <- nStock(OM)

  From <- integer(0)
  To   <- integer(0)
  for (i in seq_len(n)) {
    SPFrom <- OM@Stock[[i]]@SRR@SPFrom
    if (.IsSPFromSelfOnly(SPFrom, i, stockNames)) next
    w <- .ResolveSPFromWeights(SPFrom, stockNames, i)
    From <- c(From, rep(i, length(w$from)))
    To   <- c(To,   w$from)
  }

  comps <- .HermConnectedComponents(From, To, n)

  purrr::map(comps, \(members) {
    members    <- sort(members)
    is_source  <- purrr::map_lgl(members, \(i) .IsSPFromSelfOnly(OM@Stock[[i]]@SRR@SPFrom, i, stockNames))
    sources    <- members[is_source]
    dependents <- members[!is_source]
    weights    <- purrr::map(dependents, \(i)
      .ResolveSPFromWeights(OM@Stock[[i]]@SRR@SPFrom, stockNames, i)
    )
    list(members = members, sources = sources, dependents = dependents, weights = weights)
  })
}

.ValidateSPFrom <- function(OM) {
  stocknames <- StockNames(OM)
  nStockOM   <- length(stocknames)

  for (i in seq_len(nStockOM)) {
    st     <- stocknames[i]
    SPFrom <- OM@Stock[[i]]@SRR@SPFrom
    if (is.null(SPFrom)) next

    nm <- names(SPFrom)
    weighted <- !is.null(nm) && any(nzchar(nm))
    if (!weighted && length(SPFrom) > 1L)
      cli::cli_abort(c(
        "x" = "Stock {.val {st}} has a {.field SRR@SPFrom} of length {length(SPFrom)} with no names.",
        "i" = "Multiple sources must be given as a named vector, e.g. {.code c(Stock1 = 0.6, Stock2 = 0.4)}."
      ))

    w <- .ResolveSPFromWeights(SPFrom, stocknames, i)
    if (length(w$from) == 1L && identical(w$from, i)) next

    if (anyNA(w$from) || any(w$from < 1L | w$from > nStockOM))
      cli::cli_abort(c(
        "x" = "Stock {.val {st}} has {.field SRR@SPFrom} referencing an unknown stock.",
        "i" = "Known stocks are {.val {stocknames}}."
      ))

    if (anyDuplicated(w$from))
      cli::cli_abort(
        "Stock {.val {st}} has a duplicate source stock in {.field SRR@SPFrom}."
      )

    if (!all(is.finite(w$weight)))
      cli::cli_abort(
        "Stock {.val {st}} has a non-finite weight in {.field SRR@SPFrom}."
      )

    if (any(w$weight < 0))
      cli::cli_abort(
        "Stock {.val {st}} has a negative weight in {.field SRR@SPFrom}; weights must be non-negative."
      )

    for (src in w$from) {
      if (src == i) next
      srcSPFrom <- OM@Stock[[src]]@SRR@SPFrom
      if (!.IsSPFromSelfOnly(srcSPFrom, src, stocknames)) {
        srcOfSrc <- .ResolveSPFromWeights(srcSPFrom, stocknames, src)$from[1]
        cli::cli_abort(c(
          "x" = "{.var SRR@SPFrom} only supports one-hop sourcing, but {.val {st}} -> {.val {stocknames[src]}} -> {.val {stocknames[srcOfSrc]}} is a longer chain (or a cycle).",
          "i" = "Stock {.val {stocknames[src]}} must not itself have a non-self {.field SPFrom}."
        ))
      }
    }

    wsum <- sum(w$weight)
    if (abs(wsum - 1) > 1e-8)
      OM <- .CaptureLog(
        OM,
        string = cli::format_inline(
          "Stock {.val {st}}: {.field SRR@SPFrom} weights sum to {.val {round(wsum, 4)}}, not 1."),
        name = '.ValidateSPFrom',
        type = 'warning'
      )
  }
  OM
}

# Copy a single SPFrom source's SRR parameters and recruitment deviations into
# the dependent stock when SRR@ShareSPFrom is TRUE
.ShareSPFromSRR <- function(OM) {
  if (nStock(OM) < 2) return(OM)
  stockNames <- StockNames(OM)

  for (i in seq_len(nStock(OM))) {
    SRR <- OM@Stock[[i]]@SRR
    if (!isTRUE(SRR@ShareSPFrom)) next
    w <- .ResolveSPFromWeights(SRR@SPFrom, stockNames, i)
    if (length(w$from) != 1L || w$from == i) next

    k   <- w$from
    Src <- OM@Stock[[k]]@SRR
    st  <- stockNames[i]
    src <- stockNames[k]

    if (!identical(SRR@Model, Src@Model))
      cli::cli_abort(c(
        "x" = "Stock {.val {st}} shares {.field SRR} parameters with {.val {src}} ({.field ShareSPFrom = TRUE}), but the two use different SRR models.",
        "i" = "Use the same {.field SRR@Model}, or set {.code ShareSPFrom = FALSE} for an independent stock-recruitment curve."
      ))
    if (!identical(OM@Stock[[i]]@Ages@Classes, OM@Stock[[k]]@Ages@Classes))
      cli::cli_abort(c(
        "x" = "Stock {.val {st}} shares recruitment deviations with {.val {src}} ({.field ShareSPFrom = TRUE}), but the two have different {.field Ages@Classes}.",
        "i" = "Set {.code ShareSPFrom = FALSE} for independent recruitment deviations."
      ))

    ShareHist <- identical(SRR@Misc$RecDevHistSupplied, FALSE)
    New <- SRR
    New@Pars       <- Src@Pars
    New@SD         <- Src@SD
    New@AC         <- Src@AC
    New@RecDevInit <- Src@RecDevInit
    New@RecDevProj <- Src@RecDevProj
    if (ShareHist) New@RecDevHist <- Src@RecDevHist

    if (identical(New, SRR)) next
    OM@Stock[[i]]@SRR <- New
    OM <- .CaptureLog(
      OM,
      string = cli::format_inline(
        "Stock {.val {st}} uses the stock-recruitment parameters and {if (ShareHist) 'recruitment deviations' else 'initial and projection recruitment deviations'} of {.val {src}} ({.field SRR@ShareSPFrom})."),
      name = 'ShareSPFrom',
      type = 'assumption'
    )
  }

  for (i in seq_len(nStock(OM))) {
    if (anyNA(unlist(OM@Stock[[i]]@SRR@Pars)))
      cli::cli_abort(c(
        "x" = "Stock {.val {stockNames[i]}} has missing {.field SRR@Pars}.",
        "i" = "Provide {.field Pars}, or recruit from another stock's spawning production with {.field SPFrom} and {.code ShareSPFrom = TRUE}."
      ))
  }
  OM
}

.CheckOMReady <- function(OM) {
  problems <- character(0)

  scalar_slots <- c("nSim", "nYear", "pYear", "CurrentYear", "Seasons", "maxF")
  missing_scalars <- scalar_slots[!purrr::map_lgl(scalar_slots, \(sl) length(slot(OM, sl)) > 0)]
  if (length(missing_scalars))
    problems <- c(problems, "x" = cli::format_inline("{.var OM} is missing required value{?s} for: {.val {missing_scalars}}"))

  if (!length(OM@Complexes))
    problems <- c(problems, "x" = cli::format_inline("{.var OM@Complexes} has not been populated"))

  stock_required <- list(
    Ages             = "Classes",
    Weight           = "MeanAtAge",
    NaturalMortality = "MeanAtAge",
    Maturity         = "MeanAtAge",
    SRR              = c("Model", "R0")
  )
  stocknames <- StockNames(OM)
  for (st in seq_along(OM@Stock)) {
    nm <- stocknames[st] %||NA% paste("Stock", st)
    missing <- character(0)
    for (comp in names(stock_required)) {
      obj <- slot(OM@Stock[[st]], comp)
      if (any(purrr::map_lgl(stock_required[[comp]], \(ss) EmptyObject(slot(obj, ss)))))
        missing <- c(missing, comp)
    }
    if (length(missing))
      problems <- c(problems, "x" = cli::format_inline("Stock {.val {nm}} is missing required component{?s}: {.val {missing}}"))
  }

  fleet_required <- list(
    Effort      = "Effort",
    Selectivity = "MeanAtAge"
  )
  fleetnames <- FleetNames(OM)
  for (st in seq_along(OM@Fleet)) {
    nm_stock <- stocknames[st] %||NA% paste("Stock", st)
    for (fl in seq_along(OM@Fleet[[st]])) {
      nm_fleet <- fleetnames[fl] %||NA% paste("Fleet", fl)
      missing <- character(0)
      for (comp in names(fleet_required)) {
        obj <- slot(OM@Fleet[[st]][[fl]], comp)
        if (any(purrr::map_lgl(fleet_required[[comp]], \(ss) EmptyObject(slot(obj, ss)))))
          missing <- c(missing, comp)
      }
      if (length(missing))
        problems <- c(problems, "x" = cli::format_inline("Fleet {.val {nm_fleet}} (stock {.val {nm_stock}}) is missing required component{?s}: {.val {missing}}"))
    }
  }

  ComplexNames <- names(Complexes(OM))
  nFl <- nFleet(OM)
  for (cx in seq_along(ComplexNames)) {
    obs_cx <- OM@Obs[[cx]]
    imp_cx <- OM@Imp[[cx]]
    if (length(obs_cx) < nFl || !all(purrr::map_chr(obs_cx, class) == "obs"))
      problems <- c(problems, "x" = cli::format_inline("{.var OM@Obs} for complex {.val {ComplexNames[cx]}} is incomplete"))
    if (length(imp_cx) < nFl || !all(purrr::map_chr(imp_cx, class) == "imp"))
      problems <- c(problems, "x" = cli::format_inline("{.var OM@Imp} for complex {.val {ComplexNames[cx]}} is incomplete"))
  }

  if (length(problems)) {
    problems <- c(problems, "i" = "Supply the missing component(s) and re-run.")
    cli::cli_abort(problems, call = NULL)
  }

  invisible(OM)
}

# Populates only the Stock objects and the stock-level checks; Fleet, Obs, and
# Imp are left untouched
.PopulateStocksOnly <- function(OM, silent = TRUE, adjust_fecundity = TRUE) {
  .CheckClass(OM)
  OM <- UpdateObject(OM)
  if (is.null(OM@Stock))
    cli::cli_abort(c(
      "x" = "{.var OM} must have at least one stock",
      "i" = "See {.help MSEtool::OM} and {.help MSEtool::Stock}"
    ))
  OM <- OM |>
    .PopulateStockList(silent = silent) |>
    .UpdateSPFrom() |>
    .ValidateSPFrom() |>
    .ShareSPFromSRR() |>
    .CheckAlphaBetaSRR()
  if (adjust_fecundity)
    OM <- AdjustSeasonalFecundity(OM, silent = silent)
  OM
}

.HasFleet <- function(OM) {
  !is.null(OM@Fleet) && length(OM@Fleet) > 0
}

# unfished calculations only need populated stocks
.PopulateForUnfished <- function(OM, silent = TRUE, adjust_fecundity = TRUE) {
  if (!.HasFleet(OM))
    return(.PopulateStocksOnly(OM, silent = silent, adjust_fecundity = adjust_fecundity))
  PopulateOM(OM, silent = silent)
}
