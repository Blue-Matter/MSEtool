.GetSSSRRPars <- function(replist) {
  mainyrs <- NULL  # CRAN
  # SRR Model and Parameters
  if (replist$SRRtype == 3 || replist$SRRtype == 6) { # Beverton-Holt SR
    par <- replist$parameters[grepl("steep", rownames(replist$parameters)), ]
    h_out <- par$Value
    h_out[h_out < 0.2] <- 0.2
    h_out[h_out > 0.999] <- 0.999
    return(list(h = h_out))
  } else if (replist$SRRtype == 2) {
    par <- replist$parameters[grepl("SR_Ricker", rownames(replist$parameters)), ]
    h_out <- par$Value
    h_out[h_out < 0.2] <- 0.2
    return(list(hR = h_out))
  } else if (replist$SRRtype == 7) {
    cli::cli_abort(
      "SS3 `SRRtype == 7` currently not supported" ,.internal = TRUE
    )
    
    s_frac <- replist$parameters$Value[replist$parameters$Label == "SR_surv_Sfrac"]
    Beta <- replist$parameters$Value[replist$parameters$Label == "SR_surv_Beta"]
    s0 <- 1 / SpR0
    z0 <- -log(s0)
    z_min <- z0 * (1 - s_frac)
    h_out <- 0.2 * exp(z0 * s_frac * (1 - 0.2^Beta))
    h_out[h_out < 0.2] <- 0.2
    h_out[h_out > 0.999] <- 0.999
    return(list(h = h_out))
  } else {
    mainyrs <- replist$startyr:replist$endyr
    if (length(replist$SRRtype) && nchar(replist$SRRtype)<=1) {
      cli::cli_alert_warning(
        "`replist$SRRtype` is empty. Assuming {.val Beverton-Holt SRR}"
      )
    } else {
      cli::cli_alert_warning(
      "`replist$SRRtype` ({replist$SRRtype}) is not supported. Assuming {.val Beverton-Holt SRR}"
      )
    }
    
    if (packageVersion("r4ss") == "1.24") {
      SR_ind <- match(mainyrs, replist$recruit$year)
      SSB <- replist$recruit$spawn_bio[SR_ind]
      SSB0 <- replist$derived_quants[replist$derived_quants$LABEL == "SPB_Virgin", 2]
    } else {
      SR_ind <- match(mainyrs, replist$recruit$Yr)
      SSB <- replist$recruit$SpawnBio[SR_ind]
      SSB0 <- replist$derived_quants[replist$derived_quants$Label == "SSB_Virgin", 2]
    }
    R0 <- exp(replist$parameters$Value[replist$parameters$Label == "SR_LN(R0)"])
    rec <- replist$recruit$pred_recr[SR_ind] # recruits to age 0
    
    SpR0 <- SSB0 / (R0) #  * ifelse(season_as_years, nseas, 1))
    SRrel <- 1
    h_out <- SRopt(1, SSB, rec, SpR0, plot = FALSE, type = ifelse(SRrel == 1, "BH", "Ricker"))
    h_out[h_out < 0.2] <- 0.2
    h_out[h_out > 0.999] <- 0.999
    return(list(h = h_out))
  }
}

.GetSSRecDevsEarly <- function(replist, YearsList, Ages, st) {
  
  N1 <- N0 <- Deviation <- NULL # CRAN
  
  SSAgeClasses <- .GetSSAgeClasses(replist)
  YearsHist <- YearsList$YearsHist
  Virg <- replist$natage |>
    dplyr::filter(Era == "VIRG", `Beg/Mid` == "B", Seas == 1, Sex == st) |>
    dplyr::select(as.character(SSAgeClasses), Sex) |>
    tidyr::pivot_longer(as.character(SSAgeClasses),
      names_to = "Age", values_to = "N0"
    )

  Init <- replist$natage |>
    dplyr::filter(Yr == min(YearsHist), `Beg/Mid` == "B", Seas == 1, Sex == st) |>
    dplyr::select(as.character(SSAgeClasses), Sex) |>
    tidyr::pivot_longer(as.character(SSAgeClasses),
      names_to = "Age", values_to = "N1"
    )

  Deviations <- dplyr::left_join(Virg, Init, by = dplyr::join_by(Sex, Age)) |>
    dplyr::mutate(Deviation = N1 / N0) |>
    dplyr::mutate(
      Value = ifelse(is.finite(Deviation), Deviation, 1),
      Age = as.numeric(Age)
    ) |>
    dplyr::select(Age, Value) |>
    dplyr::arrange(Age)

  FullAgeClasses <- seq(0, by = 1 / CalcSeasons(Ages@Units), to = max(Ages@Classes))

  dev <- array(rep(Deviations$Value, each = replist$nseasons),
    dim = length(FullAgeClasses),
    dimnames = list(Age = FullAgeClasses)
  ) |>
    .ArraySubsetAge(Ages@Classes[-1])

  dev
}


.GetSSRecDevs <- function(replist, YearsList, Ages) {
  YearsHist <- YearsList$YearsHist
  Seasons   <- YearsList$Seasons
  recruit   <- replist$recruit

  Rec_main <- recruit[recruit$Yr %in% YearsHist, ]

  dev <- Rec_main$pred_recr / Rec_main$exp_recr
  dev <- array(dev,
    dim = length(dev),
    dimnames = list(Year = YearsHist[match(Rec_main$Yr, YearsHist)])
  )

  lag <- round(min(Ages@Classes) * Seasons)
  if (lag > 0) {
    # R0_virgin: total recruitment across all sexes at virgin unfished state.
    # Sum over sexes (Sex dimension) to match pred_recr which is sex-combined.
    AgeClasses <- .GetSSAgeClasses(replist)
    birthseas  <- .GetSSBirthSeas(replist)
    R0_virgin  <- dplyr::filter(
        replist$natage,
        `Beg/Mid` == "B",
        Era == "VIRG",
        Seas == birthseas
      ) |>
      tidyr::pivot_longer(as.character(AgeClasses),
        names_to  = "Age",
        values_to = "Number"
      ) |>
      dplyr::mutate(Age = as.numeric(Age)) |>
      dplyr::filter(Age == min(Age)) |>
      dplyr::summarise(Number = sum(Number)) |>
      dplyr::pull(Number)

    if (length(R0_virgin) > 0 && is.finite(R0_virgin[1]) && R0_virgin[1] > 0) {
      dev[1] <- Rec_main$pred_recr[1] / R0_virgin[1]
    }
  }

  if (Seasons == 1)
    return(dev)

  # expand for seasons
  dev <- rep(dev, each = Seasons)
  array(dev,
    dim = length(dev),
    dimnames = list(Year = YearsHist)
  )
}

.GetSSBirthSeas <- function(replist) {
  # birthseas can be a vector (e.g. c(2,3) for NPSWO) but represents a single
  # shared spawning event; using the last (latest) season as the birth season.
  if (is.null(replist$birthseas)) return(1L)
  max(replist$birthseas)
}

.GetSSR0 <- function(st, replist, YearsList) {
  
  Number <- NULL # cran checks
  
  AgeClasses <- .GetSSAgeClasses(replist)
  birthseas <- .GetSSBirthSeas(replist)

  R0 <- dplyr::filter(
    replist$natage, Sex == st,
    `Beg/Mid` == "B",
    Era == "VIRG",
    Seas == birthseas
  ) |>
    tidyr::pivot_longer(as.character(AgeClasses),
      names_to = "Age",
      values_to = "Number"
    ) |>
    dplyr::mutate(Age = as.numeric(Age)) |>
    dplyr::filter(Age == min(Age)) |>
    dplyr::pull(Number)

  nSeas <- replist$natage$Seas |>
    unique() |>
    length()
  if (length(R0) != nSeas) {
    R0Vec <- rep(0, nSeas)
    R0Vec[birthseas] <- R0
    R0 <- R0Vec
  }


  YearsAll <- c(YearsList$YearsHist, YearsList$YearsProj)
  R0 <- rep(R0, length(YearsAll))
  R0 <- R0[seq_along(YearsAll)]

  array(R0, length(R0), dimnames = list(Year = YearsAll))
}

.SS2SRR <- function(st, RepList, YearsList, Ages, nSim, R0Units = 1) {
  SD <- purrr::map(RepList, \(replist) replist$sigma_R_in) |>
    unlist() |>
    as.numeric()
  R0 <- purrr::map(RepList, \(replist) .GetSSR0(st, replist, YearsList)) |>
    List2Array("Sim", pos = 1)

  Seasons <- YearsList$Seasons
  SpawnTimeFrac <- ifelse(is.na(RepList[[1]]$Spawn_timing_in_season), 0,
                          RepList[[1]]$Spawn_timing_in_season)

  # Compute SpawnLag: timesteps between SSB evaluation (spawn_month) and
  # first appearance of recruits (birthseas). When these differ, the lag
  # implied by min(Ages@Classes) is wrong and must be overridden.
  spawn_lag <- NULL
  if (Seasons > 1 && !is.null(RepList[[1]]$Spawn_month)) {
    spawn_season <- ceiling(RepList[[1]]$Spawn_month / (12 / Seasons))
    birthseas    <- .GetSSBirthSeas(RepList[[1]])
    computed_lag <- (birthseas - spawn_season) %% Seasons
    # Default lag derived from min(Ages@Classes): Ages@MinAge / Seasons * Seasons = Ages@MinAge
    # which(seq(0,by=1/Seasons,to=MaxAge) == min(Classes)) - 1 == birthseas - 1
    default_lag  <- birthseas - 1L
    if (computed_lag != default_lag)
      spawn_lag <- computed_lag
  }

  SRR <- SRR(SD = SD, R0 = R0, SpawnTimeFrac = SpawnTimeFrac, SpawnLag = spawn_lag, Units = R0Units)

  Pars <- purrr::map(RepList, \(replist) .GetSSSRRPars(replist))
  Pars <- do.call("rbind", Pars)
  ParsList <- list(as.numeric(Pars))
  names(ParsList) <- colnames(Pars)
  SRR@Pars <- ParsList

  SRR@RecDevInit <- purrr::map(RepList, \(replist)
  .GetSSRecDevsEarly(replist, YearsList, Ages, st)) |>
    List2Array("Sim", pos = 1)

  SRR@RecDevHist <- purrr::map(RepList, \(replist)
  .GetSSRecDevs(replist, YearsList, Ages)) |>
    List2Array("Sim", pos = 1)

  AC <- log(SRR@RecDevHist) |>
    apply(1, acf, lag.max = 1, plot = FALSE, na.rm = TRUE) |>
    lapply(getElement, "acf") |>
    lapply(getElement, 2) |>
    unlist()

  AC[!is.finite(AC)] <- 0
  SRR@AC <- AC

  if (st == 2) {
    SRR@SPFrom <- 1
  }

  RecDevs <- GenRecDevs(
    SD = SRR@SD,
    AC = SRR@AC,
    Ages = Ages,
    HistYears  = YearsList$YearsHist,
    ProjYears  = YearsList$YearsProj,
    nSim = nSim,
    RecDevInit = SRR@RecDevInit,
    RecDevHist = SRR@RecDevHist
  )

  SRR@RecDevProj <- RecDevs$RecDevProj
  ProjectionYears <- YearsList$YearsProj
  dimnames(SRR@RecDevProj) <- list(
    Sim = 1:nSim,
    Year = ProjectionYears
  )
  SRR
}


