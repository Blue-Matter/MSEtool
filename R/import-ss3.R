# Detects SS3 discard_option = 3 ("all discarded fish die"), which overrides
# any length-based discard mortality curve from sizeselex's "Mort" factor.
.IsSSDiscardAllDead <- function(st, fl, replist, tol = 0.01) {
  ageselex <- replist$ageselex
  if (is.null(ageselex)) return(FALSE)

  yrs <- sort(unique(
    ageselex$Yr[ageselex$Fleet == fl & ageselex$Sex == st & ageselex$Factor == "dead_nums"]
  ))
  if (length(yrs) == 0) return(FALSE)
  yr <- yrs[length(yrs)]

  AgeCols <- names(ageselex)[suppressWarnings(!is.na(as.numeric(names(ageselex))))]

  GetFactorRow <- function(Factor) {
    row <- ageselex[ageselex$Fleet == fl & ageselex$Sex == st &
      ageselex$Factor == Factor & ageselex$Yr == yr, ]
    if (nrow(row) == 0) return(NULL)
    as.numeric(row[1, AgeCols])
  }

  Sel  <- GetFactorRow("sel_nums")
  Ret  <- GetFactorRow("sel*ret_nums")
  Dead <- GetFactorRow("dead_nums")
  if (is.null(Sel) || is.null(Ret) || is.null(Dead)) return(FALSE)

  DiscTotal <- Sel - Ret
  DiscDead  <- Dead - Ret
  valid     <- DiscTotal > 1e-6
  if (!any(valid)) return(FALSE)

  all(abs(DiscDead[valid] / DiscTotal[valid] - 1) < tol)
}


.GetSSALKAnnual <- function(st, replist, AgeClasses, LengthClasses, YearsList) {
  ALK_dim_match <- any(paste0("Seas: 1 Sub_Seas: 2 Morph: ", st) %in% dimnames(replist$ALK)[[3]])
  if (ALK_dim_match) {
    ALK <- replist$ALK[, , paste0("Seas: 1 Sub_Seas: 2 Morph: ", st)]
  } else {
    ALK <- replist$ALK[, , paste0("Seas: 1 Morph: ", (st - 1) * replist$nseasons + 1)]
  }
  if (all(!is.na(replist$lbinspop))) {
    ALK <- ALK[match(replist$lbinspop, dimnames(ALK)$Length), match(AgeClasses, dimnames(ALK)$TrueAge)]
  } else {
    lbinspop <- sort(as.numeric(dimnames(ALK)$Length))
    ALK <- ALK[match(lbinspop, dimnames(ALK)$Length), match(AgeClasses, dimnames(ALK)$TrueAge)]
  }
  ALK <- t(ALK)

  dimnames(ALK) <- list(
    Age = AgeClasses,
    Class = LengthClasses
  )

  maxALK <- apply(ALK, 1, sum)
  maxALK <- matrix(maxALK, nrow(ALK), ncol(ALK))
  ALK <- ALK / maxALK
  ALK
}

.GetSSALKSeasonal <- function(st, replist, AgeClasses, LengthClasses, YearsList) {
  nseasons <- replist$nseasons
  AgeClassesFull <- seq(0, to = max(AgeClasses), by = 1 / YearsList$Seasons)

  ALK_Out <- array(NA,
    dim = c(
      length(AgeClassesFull),
      length(LengthClasses)
    ),
    dimnames = list(
      Age = AgeClassesFull,
      Class = LengthClasses
    )
  )
  for (seas in 1:nseasons) {
    ALK <- replist$ALK[, , paste0("Seas: ", seas, " Sub_Seas: 2 Morph: ", st)]
    lbinspop <- sort(as.numeric(dimnames(ALK)$Length))
    ALK <- ALK[match(lbinspop, dimnames(ALK)$Length), ] |> t()
    names(dimnames(ALK))[1] <- "Age"

    ages <- AgeClassesFull[seq(from = seas, by = YearsList$Seasons, length.out = nrow(ALK))]
    dimnames(ALK)$Age <- ages

    rowind <- match(ages, AgeClassesFull)
    ALK_Out[rowind, ] <- ALK
  }
  .ArraySubsetAge(ALK_Out, AgeClasses)
}


.GetSSALK <- function(st, replist, AgeClasses, LengthClasses, YearsList) {
  if (YearsList$Seasons == 1) {
    return(.GetSSALKAnnual(st, replist, AgeClasses, LengthClasses, YearsList))
  }

  .GetSSALKSeasonal(st, replist, AgeClasses, LengthClasses, YearsList)
}


.SS2DiscardMortality <- function(st, fl, RepList, YearsList, Selectivity, Stock) {
  DiscardMortality <- DiscardMortality()

  DiscardMortality@MeanAtLength <- purrr::map(RepList, \(replist)
  .GetSSDiscardMortalityAtLength(st, fl, replist, YearsList, Stock)) |>
    List2Array("Sim", pos = 1) |>
    ReduceDims()

  AgeClasses <- Stock@Ages@Classes
  LengthClasses <- dimnames(DiscardMortality@MeanAtLength)$Class |> as.numeric()
  DiscardMortality@Classes <- LengthClasses

  Stock@Length <- PopulateLength(
    Length = Stock@Length,
    Ages = Stock@Ages,
    Years = c(YearsList$YearsHist, YearsList$YearsProj),
    nSim = Stock@nSim
  )

  DiscardMortality <- .MeanAtLength2MeanAtAge(
    object = DiscardMortality,
    Length = Stock@Length,
  )

  DiscardMortality@MeanAtAge <- ReduceDims(DiscardMortality@MeanAtAge)

  # Override with 100% discard mortality where SS3's own realized
  # accounting shows discard_option = 3 for this fleet (see
  # .IsSSDiscardAllDead()) 
  if (all(purrr::map_lgl(RepList, \(replist) .IsSSDiscardAllDead(st, fl, replist))))
    DiscardMortality@MeanAtAge[] <- 1

  DiscardMortality
}

.GetSSSelectivityAtAge <- function(st, fl, replist, YearsList, Stock) {
  
  Factor <- NULL # CRAN checks
  
  AgeClasses   <- Stock@Ages@Classes
  SSAgeClasses <- as.character(.GetSSAgeClasses(replist))
  YearsHist    <- YearsList$YearsHist
  nSeas        <- YearsList$Seasons
  YearsAll     <- c(YearsList$YearsHist, YearsList$YearsProj)
  
  year_to_ind <- setNames(seq_along(YearsAll), as.character(YearsAll))
  
  AgeSel_df <- replist$ageselex |>
    dplyr::filter(
      Fleet == fl,
      Sex %in% st,
      Factor == "Asel2",
      Yr %in% YearsHist
    )
  
  #  Non-seasonal
  if (replist$nseasons == 1) {
    AgeSelect <- AgeSel_df |>
      dplyr::select(dplyr::all_of(SSAgeClasses)) |>
      as.matrix() |>
      t()
    
    dimnames(AgeSelect) <- list(Age = AgeClasses, Year = YearsHist)
    col_max <- apply(AgeSelect, 2, max)
    return(sweep(AgeSelect, 2, col_max, "/"))
  }
  
  # Seasonal 
  nAge <- length(AgeClasses)
  
  age_vals     <- as.numeric(SSAgeClasses)
  SeasonalAges <- seq(min(age_vals), max(age_vals) + (nSeas - 1) / nSeas, by = 1 / nSeas)
  
  age_ind <- match(SeasonalAges, AgeClasses, nomatch = 0L)
  valid   <- age_ind > 0L
  age_ind <- age_ind[valid]
  
  MeanAtAge <- matrix(
    NA_real_,
    nrow     = nAge,
    ncol     = length(YearsHist),
    dimnames = list(Age = AgeClasses, Year = YearsHist)
  )
  
  AgeSel_long <- AgeSel_df |>
    dplyr::select(Yr, Seas, dplyr::all_of(SSAgeClasses)) |>
    tidyr::pivot_longer(
      cols      = dplyr::all_of(SSAgeClasses),
      names_to  = "Age",
      values_to = "V"
    ) |>
    dplyr::mutate(Age = as.numeric(Age)) |>
    dplyr::arrange(Yr, Age, Seas)  
  
  AgeSel_split <- split(AgeSel_long, AgeSel_long$Yr)
  
  for (yr in names(AgeSel_split)) {
    vals <- AgeSel_split[[yr]]$V[valid]
    ind1 <- year_to_ind[[yr]]
    ind2 <- year_to_ind[[as.character(as.integer(yr) + 1L)]] - 1L
    MeanAtAge[age_ind, ind1:ind2] <- vals
  }
  
  col_max <- apply(MeanAtAge, 2, max)
  sweep(MeanAtAge, 2, col_max, "/")
}

.GetSSSelectivityAtLength <- function(st, fl, replist, YearsList, Stock) {
  YearsHist <- YearsList$YearsHist

  Sel_df <- replist$sizeselex[replist$sizeselex$Fleet == fl &
    replist$sizeselex$Sex == st &
    replist$sizeselex$Factor == "Lsel" &
    replist$sizeselex$Yr %in% YearsHist, ]

  SelectYears <- Sel_df$Yr

  MidClasses <- suppressWarnings(as.numeric(colnames(Sel_df)))
  MidClasses <- MidClasses[!is.na(MidClasses)]

  SelectAtLength <- as.matrix(Sel_df[, as.character(MidClasses)])
  SelectAtLength <- t(SelectAtLength)

  dimnames(SelectAtLength) <- list(
    Class = .GetSSLengthClasses(replist),
    Year  = SelectYears
  )

  sweep(SelectAtLength, 2, apply(SelectAtLength, 2, max), "/")
}

