.SS2Weight <- function(st, RepList, YearsList, Ages, Units = "kg") {
  Weight <- Weight()
  Weight@Units <- Units

  Weight@MeanAtAge <- purrr::map(RepList, \(replist) {
    .GetSSWeightAtAge(st, replist, YearsList)
  }) |>
    List2Array("Sim", pos = 1) |>
    .ArraySubsetAge(Ages = Ages@Classes) |>
    ReduceDims()

  if (Ages@Classes |> length() != dim(Weight@MeanAtAge)[2]) {
    cli::cli_abort(c(
      "x" = "Number of age-classes for `Weight@MeanAtAge` does not match `Ages@Classes`",
      "i" = "`Weight@MeanAtAge` has {.val {dim(Weight@MeanAtAge)[2]}} age classes",
      "i" = "`Ages@Classes` has {.val {length(Ages@Classes)}} age classes"
    ))
  }

  LengthClasses  <- .GetSSLengthClasses(RepList[[1]])
  Weight@Classes <- LengthClasses

  Weight@MeanAtLength <- purrr::map(RepList, \(replist) {
    .GetSSWeightAtLength(st, replist, YearsList, LengthClasses)
  }) |>
    List2Array("Sim", pos = 1) |>
    ReduceDims()

  Weight
}

.FillValues <- function(Value) {
  for (i in seq_along(Value)[-1]) {
    if (is.na(Value[i])) {
      Value[i] <- Value[i - 1]
    }
  }
  Value
}

.ConvertSSMSeasonal <- function(M_at_age, YearsList, Ages) {
  
  AgeAnnual <- NULL # CRAN check hacks
  
  # Convert to seasonal M
  if (YearsList$TimeUnits == "quarter") {
    M_at_ageDF <- Array2DF(M_at_age)
    M_at_ageDF$AgeAnnual <- M_at_ageDF$Age
    
    AgeClassesFull <- seq(0, to = max(Ages@Classes), by = 1 / 4)
    tempDF <- data.frame(
      Age = AgeClassesFull,
      Year = rep(unique(M_at_ageDF$Year), each = length(AgeClassesFull))
    )
    
    M_at_ageDF$Value <- M_at_ageDF$Value / YearsList$Seasons
    M_at_ageDF_seasonal <- dplyr::left_join(tempDF, M_at_ageDF,
                                            by = dplyr::join_by(Age, Year)
    ) |>
      dplyr::select(-AgeAnnual) |>
      dplyr::group_by(Year) |>
      dplyr::mutate(Value = .FillValues(Value)) |>
      dplyr::ungroup()
    return(DF2Array(M_at_ageDF_seasonal))
  } else {
    cli::cli_abort("Currently only 'year' and 'quarter' are supported for `TimeUnits`", .internal = TRUE)
  }
}

.GetSSMAtAge <- function(st, replist, YearsList, Ages) {
  AgeClasses <- .GetSSAgeClasses(replist)
  
  if (!is.null(replist$Natural_Mortality)) {
    
    if (is.null(replist$Natural_Mortality$`Beg/Mid`))
      replist$Natural_Mortality$`Beg/Mid` <- 'B'
    
    if (is.null(replist$Natural_Mortality$Era))
      replist$Natural_Mortality$Era <- 'TIME'
    
    M_at_ageDF <- replist$Natural_Mortality |>
      dplyr::filter(Sex==st, 
                    `Beg/Mid`=='B',
                    Era == 'TIME')
    
    if (is.null(M_at_ageDF$Year)) {
      M_at_ageDF$Year <- M_at_ageDF$Yr
      M_at_ageDF$Yr <- NULL
    }
    
    M_at_age <- M_at_ageDF |>
      dplyr::select(dplyr::all_of(as.character(AgeClasses))) |>
      t()
    
    dimnames(M_at_age) <- list(
      Age = AgeClasses,
      Year = YearsList$YearsHist[seq_len(ncol(M_at_age))]
    )
    
    if (YearsList$TimeUnits == "year") 
      return(M_at_age)
    
    return(
      .ConvertSSMSeasonal(M_at_age, YearsList, Ages)
    )

  }
  
  M_at_ageDF <- replist$M_at_age |> dplyr::filter(Sex == st)
  if (is.null(M_at_ageDF$Year)) {
    M_at_ageDF$Year <- M_at_ageDF$Yr
  }
  Years <- unique(M_at_ageDF$Year)
  
  M_at_age <- M_at_ageDF |>
    dplyr::filter(Sex == st) |>
    dplyr::select(dplyr::all_of(as.character(AgeClasses))) |>
    t()
  
  dimnames(M_at_age) <- list(
    Age = AgeClasses,
    Year = Years
  )

  if (all(is.na(M_at_age[nrow(M_at_age), ]))) {
    endgrowth <- replist$endgrowth |> dplyr::filter(Sex == st)
    M_at_age[nrow(M_at_age), ] <- endgrowth$M[length(AgeClasses)]
  }

  if (YearsList$TimeUnits == "year") {
    return(M_at_age)
  }
  .ConvertSSMSeasonal(M_at_age, YearsList, Ages)
}

