.GetSSNatAge <- function(replist, OM, yrs = NULL, sex = 1) {
  Yr <- Time <- Seas <- NULL # CRAN
  
  if (is.null(yrs)) {
    yrs <- replist$natage |>
      dplyr::filter(Era == "TIME") |>
      dplyr::distinct(Yr) |>
      dplyr::pull(Yr)
  }

  AgeClasses <- OM@Stock[[1]]@Ages@Classes
  AgeClassesFull <- seq(0, to = max(AgeClasses), by = 1 / OM@Seasons)
  HistYears <- Years(OM, "H")

  SSN <- replist$natage |>
    dplyr::filter(Yr %in% yrs, `Beg/Mid` == "B", Sex == sex) |>
    dplyr::select(Yr, Time, Seas, as.character(.GetSSAgeClasses(replist))) |>
    tidyr::pivot_longer(as.character(.GetSSAgeClasses(replist))) |>
    dplyr::mutate(Age = as.numeric(name)) |>
    dplyr::arrange(Age)

  SSN_Ages <- SSN$Age
  Seas <- unique(SSN$Seas)
  SSN$Age <- AgeClassesFull

  SSN <- SSN |>
    dplyr::arrange(Yr, Age) |>
    dplyr::filter(Age %in% AgeClasses)


  nSeas <- length(Seas)
  nTS <- length(yrs) * nSeas
  Yrs <- SSN$Yr |> unique()

  Initial <- array(NA, c(length(AgeClasses), nTS),
    dimnames = list(
      Age = AgeClasses,
      Year = HistYears[1:nTS]
    )
  )

  i <- 0
  for (yr in Yrs) {
    for (sea in 1:nSeas) {
      i <- i + 1
      n <- SSN |> dplyr::filter(Seas == sea, Yr < yr + 1 & Yr >= yr)
      temp <- array(n$value,
        dim = c(nrow(n), 1),
        dimnames = list(
          Age = n$Age,
          Year = HistYears[i]
        )
      )
      ArrayFill(Initial) <- temp
    }
  }

  Initial
}


#' Get Reference Points from Stock Synthesis Output
#'
#' Reads biological reference points from one or more Stock Synthesis (SS3)
#' model outputs and returns the requested quantities from the
#' `derived_quants` table.
#'
#' @param SSDir One of:
#'   - A character string giving the path to an SS3 output directory,
#'     passed to [ImportSSReport()].
#'   - A `RepList` object returned by [ImportSSReport()].
#'   - A plain list in `RepList` format, i.e. `RepList[[1]]`.
#' @param Labels Character vector of `derived_quants` labels to extract.
#'   Defaults to a standard set of F, catch, and biomass reference points:
#'
#'   - `"annF_F01"`, `"Dead_Catch_F01"` — F0.1 fishing mortality and dead catch.
#'   - `"SSB_SPR"`, `"annF_SPR"`, `"Dead_Catch_SPR"` — SSB, F, and dead catch
#'     at the SPR target.
#'   - `"SSB_MSY"`, `"SPR_MSY"`, `"annF_MSY"`, `"Dead_Catch_MSY"`,
#'     `"Ret_Catch_MSY"` — SSB, SPR, F, dead catch, and retained catch at MSY.
#'
#' @return If `SSDir` contains a single model, a data frame with columns:
#'
#'   - `Label` — the `derived_quants` label.
#'   - `Value` — the point estimate, rounded to 2 decimal places.
#'   - `StdDev` — the standard deviation, rounded to 2 decimal places.
#'
#'   If `SSDir` contains multiple models, a list of such data frames, one
#'   per model.
#'
#' @seealso [ImportSSReport()]
#' @export
GetSSRefPoints <- function(SSDir, Labels = c("annF_F01",
                                                 "Dead_Catch_F01",
                                                 "SSB_SPR",
                                                 "annF_SPR",
                                                 "Dead_Catch_SPR",
                                                 "SSB_MSY",
                                                 "SPR_MSY",
                                                 "annF_MSY",
                                                 "Dead_Catch_MSY",
                                                 "Ret_Catch_MSY")) {
  if (is.character(SSDir)) {
    RepList <- ImportSSReport(SSDir)
  } else if (inherits(SSDir, 'RepList')) {
    RepList <- SSDir
  } else if (is.list(SSDir)) {
    RepList <- list(SSDir)
  } else {
    cli::cli_abort(c('x'='`SSDir` must be a path to SS3 output or a `RepList` object returned by `ImportSSReport`'))
  }

  out <- purrr::map(RepList, \(replist) {
    replist$derived_quants |> dplyr::filter(Label %in% Labels) |>
      dplyr::select(Label, Value, StdDev) |>
      dplyr::mutate(Value = round(Value, 2), StdDev = round(StdDev, 2))
  })

  if (length(out) == 1)
    return(out[[1]])
  out
}
